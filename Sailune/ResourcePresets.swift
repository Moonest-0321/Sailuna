import SwiftUI

enum ResourcePresetGroup: String, CaseIterable, Identifiable {
    case metal = "主要金屬礦物"
    case nonMetal = "主要非金屬礦物"
    case agriculture = "農林漁牧產"
    case population = "人口"
    case synthetic = "合成物"

    var id: String { rawValue }
}

struct ResourcePresetSection: Identifiable, Equatable {
    let title: String
    let content: String

    var id: String { title }
}

