struct ResourcePresetCatalogView: View {
    let allowsSelection: Bool
    let selectedID: UUID?
    let onSelect: ((ResourcePreset?) -> Void)?
    @Environment(\.dismiss) private var dismiss
    @State private var displayedPresetID: UUID?

    init(allowsSelection: Bool = false, selectedID: UUID? = nil, onSelect: ((ResourcePreset?) -> Void)? = nil) {
        self.allowsSelection = allowsSelection
        self.selectedID = selectedID
        self.onSelect = onSelect
        _displayedPresetID = State(initialValue: selectedID ?? ResourcePreset.all.first?.id)
    }

    private var displayedPreset: ResourcePreset? {
        ResourcePreset.preset(id: displayedPresetID)
    }

    var body: some View {
        NavigationSplitView {
            List(selection: $displayedPresetID) {
                ForEach(ResourcePresetGroup.allCases) { group in
                    SwiftUI.Section(group.rawValue) {
                        ForEach(ResourcePreset.all.filter { $0.group == group }) { preset in
                            VStack(alignment: .leading, spacing: 3) {
                                Text(preset.title).font(.headline)
                                Text(preset.summary).font(.caption).foregroundStyle(.secondary)
                            }
                            .tag(preset.id)
                        }
                    }
                }
            }
            .navigationTitle("資源")
        } detail: {
            if let displayedPreset {
                ResourcePresetDetailView(preset: displayedPreset)
                    .safeAreaInset(edge: .bottom) {
                        if allowsSelection {
                            HStack {
                                Button("不選擇") {
                                    onSelect?(nil)
                                    dismiss()
                                }
                                Spacer()
                                Button("選擇\(displayedPreset.title)") {
                                    onSelect?(displayedPreset)
                                    dismiss()
                                }
                                .buttonStyle(.borderedProminent)
                            }
                            .padding()
                            .background(.bar)
                        }
                    }
            } else {
                ContentUnavailableView("請選擇資源", systemImage: "shippingbox")
            }
        }
        .frame(minWidth: 820, minHeight: 620)
        .toolbar {
            Button("關閉") { dismiss() }
        }
    }
}

